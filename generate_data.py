"""## Part B — Classification models

### Model Training and Evaluation

We will now train two classification models: Logistic Regression and a Decision Tree Classifier. Both models will be trained on the preprocessed `X_train_processed` and `y_train` data, and evaluated on `X_test_processed` and `y_test`. To ensure comparability, we will use `random_state=42` for the Decision Tree Classifier.

Evaluation metrics will include:
- **Confusion Matrix:** To understand the types of errors made (True Positives, True Negatives, False Positives, False Negatives).
- **Accuracy:** The proportion of correctly classified instances.
- **Precision:** The proportion of positive identifications that were actually correct.
- **Recall (Sensitivity):** The proportion of actual positives that were identified correctly.
- **F1-Score:** The harmonic mean of precision and recall, providing a balance between the two.
- **ROC Curve and AUC (Area Under the Receiver Operating Characteristic Curve):** To assess the model's ability to distinguish between classes across various threshold settings.
"""

from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score, confusion_matrix, roc_curve
import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd

# Initialize models
log_reg = LogisticRegression(random_state=42, solver='liblinear') # 'liblinear' is good for small datasets and handles L1/L2 penalties
