"""### Imputation of `credit_bureau_score`

**Justification for Imputation Strategy:**

The `credit_bureau_score` has 20% missing values, which we've identified as 'thin-file' applicants. For these applicants, alternative data sources (like `upi_monthly_inflow_inr`) are particularly important. Instead of dropping these rows (which would exclude a significant segment of applicants our model should serve), we impute the missing `credit_bureau_score` values.

We choose to impute with the **median** of the non-missing `credit_bureau_score` values. The median is preferred over the mean for skewed distributions or when outliers are present, as it is more robust to extreme values. This ensures that the imputed values do not unduly influence the overall distribution of the scores. More importantly, this median is calculated *exclusively* from the **training set**.

Using the training set's median to impute both training and test sets is a critical step to prevent **data leakage**. If the median were calculated from the entire dataset (training + test), information about the test set's distribution would implicitly be used during the training phase, leading to an over-optimistic assessment of the model's performance on unseen data. By deriving the imputation value solely from the training data, we simulate a real-world scenario where the model would encounter new, unseen data (the test set) and apply transformations learned only from its training experience.
"""

# Calculate the median credit_bureau_score from the training set only
