"""### Split into Train/Test and Impute Missing Values

**Justification for Stratification:**

Stratifying the train-test split on the `default` column is crucial because the `default` label represents the target variable, and it is often imbalanced (as seen, the default rate is 20.25%, meaning a majority of applicants do not default). Without stratification, a random split might result in one of the sets having a significantly different proportion of defaulted cases compared to the other or the overall dataset. This can lead to:
- **Biased model training:** The training set might not adequately represent the true distribution of defaults, leading to a model that performs poorly on unseen data.
- **Inaccurate evaluation:** The test set might not accurately reflect the model's performance on the actual population, especially for the minority class (defaults).

Stratification ensures that both the training and test sets maintain approximately the same proportion of default and non-default applicants as the original dataset, leading to more robust model training and reliable evaluation metrics.
"""

from sklearn.model_selection import train_test_split

# Separate features (X) and target (y)
