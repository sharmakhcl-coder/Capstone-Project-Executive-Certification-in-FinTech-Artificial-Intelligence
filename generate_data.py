y_pred_dec_tree = dec_tree.predict(X_test_processed)
y_prob_dec_tree = dec_tree.predict_proba(X_test_processed)[:, 1]

# Function to evaluate and store metrics
def evaluate_model(y_true, y_pred, y_prob, model_name):
    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred)
    recall = recall_score(y_true, y_pred)
    f1 = f1_score(y_true, y_pred)
    roc_auc = roc_auc_score(y_true, y_prob)
    cm = confusion_matrix(y_true, y_pred)
    return {
        'Model': model_name,
        'Accuracy': accuracy,
        'Precision': precision,
        'Recall': recall,
        'F1-Score': f1,
        'ROC-AUC': roc_auc,
        'Confusion Matrix': cm
    }

# Evaluate both models
log_reg_metrics = evaluate_model(y_test, y_pred_log_reg, y_prob_log_reg, 'Logistic Regression')
