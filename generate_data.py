"""### Encoding Categorical Features and Scaling Numeric Features

**1. Encoding `employment_type`:**

The `employment_type` feature is a categorical variable with three nominal categories: "salaried", "self_employed", and "gig". One-hot encoding is chosen for this feature. This method creates new binary columns for each category, where a '1' indicates the presence of that category and '0' indicates its absence. This approach is suitable because it avoids imparting any ordinal relationship between categories, which is appropriate for nominal data.

**2. Scaling Numeric Features with `StandardScaler`:**

Numeric features often have different scales and ranges, which can disproportionately influence machine learning models that rely on distance metrics (e.g., K-Nearest Neighbors, SVMs) or gradient descent optimization (e.g., Logistic Regression, Neural Networks). `StandardScaler` is used to transform features by removing the mean and scaling to unit variance. This results in data with a mean of 0 and a standard deviation of 1. This standardization is applied to all numeric features (excluding the `applicant_id` which is an identifier and the `is_thin_file` binary flag).

**Prevention of Data Leakage:**

Crucially, the `StandardScaler` is `fit` **only on the training data (`X_train`)**. The mean and standard deviation learned from the training set are then used to `transform` both the training set and the test set (`X_test`). This practice is vital to prevent data leakage, ensuring that the test set remains truly unseen by the model during the preprocessing stage and provides an unbiased evaluation of the model's performance on new data.
"""

from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

